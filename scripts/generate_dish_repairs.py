def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", nargs="*", default=[])
    parser.add_argument("--limit", type=int)
    parser.add_argument("--refresh", action="store_true")
    parser.add_argument("--shard-count", type=int, default=1)
    parser.add_argument("--shard-index", type=int, default=0)
    parser.add_argument("--no-optimize", action="store_true")
    args = parser.parse_args()

    key = json.loads(ARKCLI_KEY.read_text(encoding="utf-8"))["api_key"]
    dishes = {
        dish["name"]: dish
        for dish in json.loads(DATA.read_text(encoding="utf-8"))
    }
    env = os.environ.copy()
    env["ARK_SEEDREAM_API_KEY"] = key
    env["ARK_SEEDREAM_MODEL"] = "doubao-seedream-5.5"

    selected = [
        item
        for index, item in enumerate(REPAIRS)
        if (not args.only or item[0] in args.only)
        and index % args.shard_count == args.shard_index
    ]
    if args.limit:
        selected = selected[: args.limit]
    failed: list[tuple[str, str]] = []
    for index, (dish, slug, detail) in enumerate(selected, 1):
        save_dir = OUT / slug
        existing = sorted(save_dir.rglob("*.png"))
        if existing and not args.refresh:
            print(f"[{index}/{len(selected)}] SKIP {dish} {existing[0]}", flush=True)
            continue
        env["ARK_SEEDREAM_SAVE_PATH"] = str(save_dir)
        vessel = VESSELS[dish]
        cuisine = dishes[dish]["cuisine"]
        cuisine_style = CUISINE_STYLE[cuisine]
        command = [
            str(NODE),
            str(GENERATE),
            "--prompt",
            detail
            + PORTION_EXTRA.get(dish, "")
            + f"地域与菜系气质：{cuisine_style}。"
            + f"盛器严格采用：{vessel}；不要与其他菜共用同一种盘子。"
            + STYLE,
            "--size",
            "1536x1152",
            "--mode",
            "text-to-image",
            "--watermark",
            "false",
            "--optimize",
            "false" if args.no_optimize else "true",
            "--enable_web_search",
            "false",
            "--response_format",
            "png",
        ]
        result = subprocess.run(
            command,
            cwd=ROOT,
            env=env,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=180,
        )
        if result.returncode:
            failed.append((dish, (result.stdout or result.stderr).strip()[:300]))
            print(f"[{index}/{len(selected)}] FAIL {dish}", flush=True)
            continue
        try:
            payload = json.loads(result.stdout)
            image = payload["images"][0]["local_path"]
            print(f"[{index}/{len(selected)}] OK {dish} {image}", flush=True)
        except Exception as exc:  # noqa: BLE001 - keep going and report the batch
            failed.append((dish, f"parse: {exc}"))
            print(f"[{index}/{len(selected)}] FAIL {dish} parse", flush=True)

    print(f"done ok={len(selected) - len(failed)} failed={len(failed)}", flush=True)
    for dish, error in failed:
        print(f"FAILED {dish}: {error}", flush=True)
    if failed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
