    extra = [k for k in merged if k not in amounts]
    if extra:
        print("注意: 以下步骤菜名不在 amounts(忽略):", extra)

    json.dump(merged, open(STEPS, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    lens = [len(v) for v in merged.values()]
    print("写入 howto-steps.json 共", len(merged), "条; 步骤数范围", min(lens), "-", max(lens), "平均", sum(lens)//len(lens))
    # 列出有 2 步的，便于复核
    short = [(k, len(v)) for k, v in merged.items() if len(v) <= 2]
    print("≤2 步的菜:", short)

