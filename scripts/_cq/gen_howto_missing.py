def main():
    data = json.load(open(OUT, encoding='utf-8'))
    before = len(data)
    added = 0
    for name, lst in MISSING.items():
        if name in data:
            continue  # 不覆盖已有
        data[name] = lst
        added += 1
    # 稳定排序：保持原有在前，新增按菜名排序更整洁
    ordered = {k: data[k] for k in sorted(data.keys(), key=lambda x: (x not in MISSING, x))}
    json.dump(ordered, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('已有条目:', before, ' 本次新增:', added, ' 合计:', len(ordered))
    # 校验每一项都含数字/单位
    import re
    bad = 0
    for n, lst in ordered.items():
        for s in lst:
            if not re.search(r'[0-9０-９]|g|克|ml|毫升|个|只|条|根|片|瓣|块|棵|颗|粒|把|支|袋|盒|头|朵|尾|张|串|勺|杯|碗|斤|两|约|适量|少许', s):
                bad += 1
                print('  可疑项:', n, '->', s)
    print('无数字/单位的项:', bad)

if __name__ == '__main__':
    main()
