def build(name, main, keys, cuisine, tags, spicy, minutes):
    ings = [x.strip() for x in main.split('、') if x.strip()] + ['盐 少许', '食用油 1 勺', '葱花 少许']
    steps = [
        f'备料：{main} 分别洗净、切好，按用量分盘摆放，避免下锅时手忙脚乱。',
        keys[0], keys[1], keys[2],
        '起锅前尝一次咸淡，再按自家口味补盐、糖或醋；喜欢更香可淋一勺热油激出香气。',
        '装盘时把主料朝上、汤汁浇匀，趁热上桌；吃不完的密封冷藏，隔夜加热再吃。',
    ]
    return {
        'name': name, 'cuisine': cuisine,
        'desc': f'{tags[0]}风味，{main.split("、")[0]}为主，家里也能做',
        'tags': tags, 'spicy': spicy, 'minutes': minutes,
        'ingredients': ings, 'steps': steps,
    }


def call(path, method='GET', body=None):
    req = urllib.request.Request(BASE + path, method=method,
                                 data=json.dumps(body).encode() if body else None,
                                 headers={'Content-Type': 'application/json'})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode())


def main():
    existing = {d['name'] for d in call('/api/dishes')}
    items = []
    for name, m, k in XINJIANG:
        items.append(build(name, m, k, 'xinjiang', ['新疆菜', '西域风味'], 1, 40))
    for name, m, k in SNACK:
        items.append(build(name, m, k, 'sichuan', ['川渝小吃', '山城味道'], 2, 20))
    added = skipped = 0
    for it in items:
        if it['name'] in existing:
            skipped += 1
            continue
        call('/api/dishes', 'POST', it)
        added += 1
    print('新疆菜', len(XINJIANG), '道 / 川渝小吃', len(SNACK), '道；新增', added, '跳过', skipped)


if __name__ == '__main__':
    main()
