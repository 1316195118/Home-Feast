def main():
    live = json.load(open(LIVE, encoding="utf-8"))
    live_names = set(d["name"] for d in live if d.get("name"))
    local = json.load(open(os.path.join(BASE, "data", "dishes.json"), encoding="utf-8"))
    local_names = set(d["name"] for d in local if d.get("name"))
    missing = sorted(live_names - local_names)
    print(f"线上独有菜: {len(missing)}")

    # 校验脚本内 CUSTOM 是否覆盖全部 missing
    custom_keys = set(CUSTOM.keys())
    not_covered = [m for m in missing if m not in custom_keys]
    if not_covered:
        print("!!! 以下线上菜未生成克数(脚本需补):", not_covered)
        sys.exit(1)
    extra = [k for k in custom_keys if k not in live_names]
    if extra:
        print("注意: 以下脚本菜名不在线上清单(将被忽略不影响):", extra)

    # 合并进 howto-amounts.json
    data = json.load(open(JSON_PATH, encoding="utf-8"))
    before = len(data)
    for name in missing:
        data[name] = CUSTOM[name]
    with open(JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print(f"howto-amounts.json: {before} -> {len(data)} 条")

    # 校验：每项都含数字或单位
    import re
    bad = []
    for k, v in data.items():
        for s in v:
            if not re.search(r"[0-9０-９]|g|克|ml|毫升|个|只|条|根|片|瓣|块|棵|颗|粒|把|支|袋|盒|头|朵|尾|张|串|勺|杯|碗|斤|两|半|适量|少许", s):
                bad.append((k, s))
    print("缺数字/单位项:", len(bad))

    # 最终覆盖核对
    final = set(data.keys())
    print("线上 184 道中已被 howto 覆盖:", len(live_names & final), "/ 184")
    print("本地 109 道中已被 howto 覆盖:", len(local_names & final), "/ 109")

if __name__ == "__main__":
    main()
