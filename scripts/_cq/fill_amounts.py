n_full = n_tune = 0
for d in arr:
    if d['name'] in FULL:
        d['ingredients'] = list(FULL[d['name']])
        n_full += 1
        continue
    ings = d.get('ingredients') or []
    if not ings:
        continue
    out = []
    for x in ings:
        if x in TUNE:
            x = TUNE[x]
            n_tune += 1
        out.append(x)
    d['ingredients'] = out

print(f'整表重写 {n_full} 道，微调 {n_tune} 处')

# 复查：是否还有无数字的配料
