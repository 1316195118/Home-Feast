#!/usr/bin/env python3
"""发布脚本：版本号只在「推送」时递增，平时部署只暂存更新说明。

版本规则（用户约定）：
    1.0.0.1 → 1.0.0.2 → … → 1.0.0.9 → 1.0.1.0 → … → 1.0.9.9 → 1.1.0.0
    末位每发布一次 +1，满 10 向高位进位（十进制进位，段数始终是 4）。

工作流（用户 2026-11-15 定）：
    平时改完想上线：
        python scripts/release.py --note "这次改了什么" --deploy
        → 说明记进 docs/PENDING.md，版本号不变，线上仍显示当前版本 + 最新一条说明

    攒够了、用户明确说「推送」时：
        python scripts/release.py --publish
        → 把 PENDING 里的说明合并成一条 CHANGELOG、递增版本号、编译、
          git commit、git push、部署（加 --no-deploy 可跳过部署）

    python scripts/release.py --show     # 当前版本 + 待发布条数
    python scripts/release.py --note "..." --no-deploy   # 只记录说明 + 编译
"""
import argparse
import datetime
import json
import os
import re
import subprocess
import sys

sys.stdout.reconfigure(encoding='utf-8')

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION_FILE = os.path.join(ROOT, 'VERSION')
CHANGELOG = os.path.join(ROOT, 'CHANGELOG.md')
PENDING = os.path.join(ROOT, 'docs', 'PENDING.md')
GEN_FILE = os.path.join(ROOT, 'internal', 'api', 'version_gen.go')
CHANGELOG_GO = os.path.join(ROOT, 'internal', 'api', 'changelog_gen.go')
BIN = os.path.join(ROOT, 'menu-linux')
DEPLOY = os.path.join(ROOT, 'scripts', '_cq', 'deploy_menu4.py')

PENDING_HEADER = '''# 待发布说明

> 每次部署用 `--note` 记一条，版本号不变；用户确认后 `--publish` 一次性发版并推送。

'''


def read_version():
    with open(VERSION_FILE, encoding='utf-8') as f:
        v = f.read().strip()
    if not re.fullmatch(r'\d+(\.\d+){3}', v):
        raise SystemExit(f'VERSION 内容不合法: {v!r}（应为 1.0.0.0 这样的四段数字）')
    return v


def bump(v):
    """末位 +1，满 10 向高位进位；最高位到 10 就保留 10（不再扩段）。"""
    parts = [int(x) for x in v.split('.')]
    i = len(parts) - 1
    parts[i] += 1
    while i > 0 and parts[i] >= 10:
        parts[i] = 0
        parts[i - 1] += 1
        i -= 1
    return '.'.join(str(p) for p in parts)


def write_version(v):
    with open(VERSION_FILE, 'w', encoding='utf-8', newline='') as f:
        f.write(v + '\n')


def read_pending():
    """返回 [(时间, 说明), ...]，文件名不存在时为空。"""
    if not os.path.exists(PENDING):
        return []
    s = open(PENDING, encoding='utf-8').read()
    blocks = re.findall(r'^## (.+?)\n\n(.*?)(?=^## |\Z)', s, re.M | re.S)
    return [(t.strip(), body.strip()) for t, body in blocks if body.strip()]


def append_pending(note, now):
    s = open(PENDING, encoding='utf-8').read() if os.path.exists(PENDING) else PENDING_HEADER
    if not s.lstrip().startswith('#'):
        s = PENDING_HEADER + s
    entry = f"## {now.strftime('%Y-%m-%d %H:%M')}\n\n{note.strip()}\n\n"
    m = re.search(r'^## ', s, re.M)
    s = (s[:m.start()] + entry + s[m.start():]) if m else (s.rstrip() + '\n\n' + entry)
    open(PENDING, 'w', encoding='utf-8', newline='').write(s)


def clear_pending():
    open(PENDING, 'w', encoding='utf-8', newline='').write(PENDING_HEADER)


def append_changelog(v, note, now):
    line = f'## {v} · {now.strftime("%Y-%m-%d")}\n\n{note.strip()}\n\n'
    s = open(CHANGELOG, encoding='utf-8').read() if os.path.exists(CHANGELOG) else '# 更新记录\n\n'
    m = re.search(r'^## \d', s, re.M)
    s = (s[:m.start()] + line + s[m.start():]) if m else (s.rstrip() + '\n\n' + line)
    open(CHANGELOG, 'w', encoding='utf-8', newline='').write(s)


def gen_go(v, note, now):
    # 内嵌进二进制的说明是纯文本（设置页直接展示），把 Markdown 的 **加粗** 换成【】，
    # 否则用户会看到一对星号。CHANGELOG 里仍保留标准 Markdown。
    plain = re.sub(r'\*\*(.+?)\*\*', r'【\1】', note.strip())
    body = f'''// Code generated by scripts/release.py; DO NOT EDIT.

package api

func init() {{
\tVersion = {json.dumps(v, ensure_ascii=False)}
\tReleaseNote = {json.dumps(plain, ensure_ascii=False)}
\tBuildTime = {json.dumps(now.strftime("%Y-%m-%d %H:%M:%S"), ensure_ascii=False)}
}}
'''
    open(GEN_FILE, 'w', encoding='utf-8', newline='').write(body)


def parse_changelog():
    """把 CHANGELOG.md 解析成 [{version, date, sections:[{kind, lines}]}]。"""
    s = open(CHANGELOG, encoding='utf-8').read()
    out = []
    for m in re.finditer(r'^## (\S+) · (\S+)\n\n(.*?)(?=^## |\Z)', s, re.M | re.S):
        ver, date, body = m.group(1), m.group(2), m.group(3).strip()
        sections = []
        for sm in re.finditer(r'^\*\*(.+?)\*\*\s*\n(.*?)(?=^\*\*|\Z)', body, re.M | re.S):
            kind = sm.group(1).strip()
            lines = [ln.strip()[1:].strip() for ln in sm.group(2).splitlines() if ln.strip().startswith('-')]
            if lines:
                sections.append({'kind': kind, 'lines': lines})
        if sections:
            out.append({'version': ver, 'date': date, 'sections': sections})
    return out


def gen_changelog_go():
    """把历史版本记录嵌进二进制，供「版本更新」弹窗展示。"""
    data = parse_changelog()
    payload = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    body = ('// Code generated by scripts/release.py; DO NOT EDIT.\n\n'
            'package api\n\n'
            '// changelogJSON 是 CHANGELOG.md 的结构化副本。\n'
            f'const changelogJSON = {json.dumps(payload, ensure_ascii=False)}\n')
    open(CHANGELOG_GO, 'w', encoding='utf-8', newline='').write(body)
    return len(data)


# 目标架构 → Go GOARCH / GOARM。纯 Go、无 CGO，全部可交叉编译。
# amd64 沿用 menu-linux 这个名字，保证现有部署脚本与流程零改动。
ARCHES = {
    'amd64': {'GOARCH': 'amd64'},
    'arm64': {'GOARCH': 'arm64'},
    'armv7': {'GOARCH': 'arm', 'GOARM': '7'},
}


def bin_for(arch):
    return BIN if arch == 'amd64' else os.path.join(ROOT, f'menu-linux-{arch}')


def build(arch='amd64'):
    if arch not in ARCHES:
        raise SystemExit(f'不支持的架构 {arch}，可选：{", ".join(ARCHES)} / all')
    env = dict(os.environ, GOOS='linux', CGO_ENABLED='0', **ARCHES[arch])
    out = bin_for(arch)
    cmd = ['go', 'build', '-trimpath', '-ldflags', '-s -w', '-o', out, './cmd/menu']
    print(f'编译 {arch}:', ' '.join(cmd))
    subprocess.run(cmd, cwd=ROOT, env=env, check=True)
    print(f'  产物 {os.path.basename(out)}（{os.path.getsize(out) / 1024 / 1024:.1f} MB）')
    return out


def build_all():
    """一次产出 amd64 / arm64 / armv7 三个二进制，供不同设备取用。"""
    for arch in ARCHES:
        build(arch)


def deploy():
    subprocess.run([sys.executable, DEPLOY], cwd=ROOT, check=True)


def run_git(args, capture=False):
    return subprocess.run(['git'] + args, cwd=ROOT, check=True,
                          text=True, capture_output=capture)


def publish(do_deploy=True, arch='amd64'):
    entries = read_pending()
    if not entries:
        raise SystemExit('没有待发布说明，先用 --note 记录这次改了什么')

    cur = read_version()
    v = bump(cur)
    now = datetime.datetime.now()

    # 多个时间块的说明合并到同一个版本下，保留各自小标题便于回看
    if len(entries) == 1:
        note = entries[0][1]
    else:
        note = '\n\n'.join(f'**{t}**\n\n{body}' for t, body in entries)

    write_version(v)
    append_changelog(v, note, now)
    gen_go(v, note, now)
    clear_pending()
    n = gen_changelog_go()
    print(f'版本记录已嵌入：{n} 条')
    print(f'版本 {cur} → {v}（合并 {len(entries)} 条说明）')

    build_all() if arch == 'all' else build(arch)
    if do_deploy:
        deploy()

    # 提交与推送：用户明确要求「推送时才更新版本号」，所以只在 publish 里做
    run_git(['add', '-A'])

    # 说明是三段式（**新增** / **修复** / **优化**），标题取第一条实际内容
    def first_summary(body):
        for line in body.splitlines():
            text = line.strip().lstrip('-').strip()
            if not text or text.startswith('**'):
                continue
            return text[:60]
        return '常规更新'

    msg = f'v{v}：{first_summary(entries[-1][1])}'
    run_git(['commit', '-m', msg])
    print('已提交:', msg)
    run_git(['push', 'origin', 'main'])
    print('已推送到 GitHub')
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--note', help='本次更新说明（记入 docs/PENDING.md，不递增版本）')
    ap.add_argument('--show', action='store_true', help='显示当前版本与待发布条数')
    ap.add_argument('--publish', action='store_true', help='正式发版：递增版本 + CHANGELOG + 编译 + 提交 + 推送')
    ap.add_argument('--no-build', action='store_true', help='不编译')
    ap.add_argument('--arch', default='amd64',
                    help='编译架构：amd64（默认）/ arm64 / armv7 / all（一次全编）')
    ap.add_argument('--no-deploy', action='store_true', help='不部署')
    a = ap.parse_args()

    if a.show:
        pending = read_pending()
        print(f'当前版本 {read_version()}，待发布 {len(pending)} 条')
        for t, body in pending:
            print(f'  [{t}] {body.splitlines()[0][:60]}')
        return

    if a.publish:
        publish(do_deploy=not a.no_deploy, arch=a.arch)
        return

    if not a.note:
        raise SystemExit('请用 --note 写清本次更新内容，或用 --publish 正式发版')

    now = datetime.datetime.now()
    append_pending(a.note, now)
    # 版本号保持不变，但让线上「关于」显示最新一条说明
    gen_go(read_version(), a.note, now)
    gen_changelog_go()
    print(f'说明已暂存（版本仍为 {read_version()}）')

    if not a.no_build:
        build_all() if a.arch == 'all' else build(a.arch)
    if not a.no_deploy:
        deploy()
    print('提醒：未提交、未推送。确认后执行 release.py --publish')


if __name__ == '__main__':
    main()
