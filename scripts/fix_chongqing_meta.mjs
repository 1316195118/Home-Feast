async function main() {
  const r = await fetch(`${BASE}/api/dishes`)
  const data = await r.json()
  const dishes = data.dishes || data
  const byName = Object.fromEntries(dishes.map((d) => [d.name, d]))

  let ok = 0
  const problems = []
  for (const [name, [tags, minutes, desc]] of Object.entries(META)) {
    const d = byName[name]
    if (!d) { problems.push([name, '目标系统找不到']); continue }
    try {
      const res = await fetch(`${BASE}/api/dishes/${d.id}`, {
        method: 'PUT',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ tags, minutes, desc }),
      })
      const j = await res.json()
      if (!res.ok) throw new Error(j.error || res.status)
      ok++
    } catch (e) {
      problems.push([name, e.message])
    }
  }
  console.log(`更新成功: ${ok} / ${Object.keys(META).length}`)
  if (problems.length) console.log('问题:', problems)
}

main().catch((e) => { console.error(e); process.exit(1) })
